/** Security headers (.claude/rules/security.md). */
export const SECURITY_HEADERS: Array<[string, string]> = [
  ["X-Frame-Options", "DENY"],
  ["X-Content-Type-Options", "nosniff"],
  ["Referrer-Policy", "origin-when-cross-origin"],
  ["Strict-Transport-Security", "max-age=31536000; includeSubDomains"],
];

const escapeRegex = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** "/ueber-uns#team" → "/ueber-uns/#team" (the export uses trailing slashes). */
export function exportPath(destination: string) {
  const [path, hash] = destination.split("#");
  const withSlash = path.endsWith("/") ? path : `${path}/`;
  return hash ? `${withSlash}#${hash}` : withSlash;
}

/** One RewriteRule per redirect. Old Contao URLs may end in ".html" or "/". */
export function rewriteRule([source, destination]: [string, string]) {
  const wildcard = source.endsWith("/:slug*");
  const base = escapeRegex((wildcard ? source.slice(0, -"/:slug*".length) : source).slice(1));
  const pattern = wildcard ? `^${base}(/.*)?$` : `^${base}(\\.html)?/?$`;
  const target = exportPath(destination);
  // NE: keep "#" unescaped in the target
  return `RewriteRule ${pattern} ${target} [R=301,L${target.includes("#") ? ",NE" : ""}]`;
}

export function htaccess() {
  return [
    "# Generated by scripts/write-htaccess.mts after `next build` – do not edit by hand.",
    "Options -Indexes",
    "DirectoryIndex index.html",
    "ErrorDocument 404 /404.html",
    "AddDefaultCharset utf-8",
    "",
    "<IfModule mod_headers.c>",
    ...SECURITY_HEADERS.map(([key, value]) => `  Header always set ${key} "${value}"`),
    "  # Hashed build files never change",
    '  <If "%{REQUEST_URI} =~ m#^/_next/static/#">',
    '    Header set Cache-Control "public, max-age=31536000, immutable"',
    "  </If>",
    "</IfModule>",
    "",
    "<IfModule mod_deflate.c>",
    "  AddOutputFilterByType DEFLATE text/html text/css text/plain text/xml text/javascript application/javascript application/json application/xml image/svg+xml",
    "</IfModule>",
    "",
    "<IfModule mod_rewrite.c>",
    "  RewriteEngine On",
    "  # Always HTTPS",
    "  RewriteCond %{HTTPS} !=on",
    "  RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [R=301,L,NE]",
    "  # Old ausdauer-shop.de URLs",
    ...LEGACY_REDIRECTS.map((r) => `  ${rewriteRule(r)}`),
    "</IfModule>",
    "",
  ].join("\n");
}
